package com.example.commutemood.domain;

/**
 * 通勤记录所依据路线结果的来源（成员 D，任务 D02/D03）。
 *
 * <p>用于"拒绝演示结果进入真实统计"：只有 {@link #REAL} 的快照才应计入真实通勤趋势，
 * {@link #DEMO} 表示路线来自演示/模拟提供器（如高德未配置或调用失败时的回退），
 * 不得写入真实统计。{@link #UNKNOWN} 用于历史数据（迁移前没有来源字段）以及
 * 快照尚未携带来源信息时的兜底口径，趋势侧应显式标记而非当作真实评分。
 *
 * <p>注意：来源的"生产"在 B 的路线领域模型/快照里（B02 来源贯通、B04 快照含来源），
 * D 只负责在通勤记录里消费并存储该来源。B 交付快照来源字段前，D 侧解析结果统一为
 * {@link #UNKNOWN}，接入点集中在 CommuteService 的来源解析方法，便于后续一处对接。
 */
public enum RouteSource {
    /** 真实外部路线服务（如高德）产出。 */
    REAL,
    /** 演示/模拟路线，不得进入真实统计。 */
    DEMO,
    /** 来源未知（历史数据或快照未携带来源），按未知口径处理。 */
    UNKNOWN
}
